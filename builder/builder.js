/* ==========================================================================
   rux-ds — BUILDER                                    roadmap §4.12, creator 3
   --------------------------------------------------------------------------
   The page builder's behaviour, for builder.html (generated by
   tools/build-builder.mjs). Hand-written, and deliberately NOT in js/:
   tools/new-project.sh copies js/*.js into every consumer's vendor/, and
   tools/lib/stats.mjs counts js/ as the published module set. This file
   belongs to one page in this repository.

   WHAT IT DOES, this stage: fetches builder/blocks.json, offers the ten
   templates and the answers new-project.sh asks, and keeps ONE PAGE MODEL
   PER TEMPLATE (builder/page.mjs) — the template's own blocks to begin with,
   then whatever the reader adds from the catalogue, moves or removes. The
   model is composed into the page by composePage, which puts every instance
   through instanceOf so a block placed twice keeps its labels bound to its
   own radios, and the preview shows the result in an iframe at a chosen
   width. Every block on the page is offered by label, its editable text is
   listed, and an edit is written back through applyTextEdits, keyed by the
   INSTANCE (`id@n`) so two copies edit apart. Every one of those actions can
   be UNDONE, and the whole session survives a reload as a draft.

   ONE HISTORY, AND ONE ENTRY PER ACTION. builder/session.mjs holds the
   history and the draft; this file decides what an action IS. Every user
   action goes through change() or typed(), which snapshot before, run the
   whole action — Remove touches both the edits and the model, and that is
   ONE entry, not two — and record only if something actually moved. The
   low-level setters below (setEdit, dropEdits, setPage) never touch history
   themselves, which is what keeps an action atomic. Navigation records
   nothing: switching template, slot, block, catalogue or width is not a
   change, so undo and redo instead SELECT the template the action happened
   on, and say so in the button's name.

   THE PREVIEW IS A BLOB URL, not srcdoc. A srcdoc document inherits the
   parent's base URL, so `href="#main-content"` — every template's skip link
   — can resolve to builder.html#main-content and navigate the frame away. A
   blob: document created here has this origin and a URL of its own, so
   fragments stay put and css/, js/ and assets/ load by absolute URL. The
   URL is revoked once the frame has loaded it.

   NOTHING HERE CONSTRUCTS rux-- MARKUP. The chrome is in the generated page,
   where check-classes reads it; this file only fills <select>s, toggles
   aria-pressed and disabled, writes an iframe's src and size, and CLONES the
   four <template>s builder.html ships — a text field, the no-fields line,
   and the two notices. Real component markup is authored in the generator
   and cloned here, never assembled out of class-name strings.

   AND IT CAN BE TAKEN AWAY. Two delivery paths, no third: download the page
   for a project that exists, or copy the whole <main> to replace one; or, for
   a project that does not exist yet, copy the exact new-project.sh command
   built from the answers. THE SCRIPT STAYS THE ONE PROJECT CREATOR — the
   builder writes a page, never a project — and tools/check-parity.mjs holds
   exportPage to the script's own page-writing lines, run per template.

   NOT YET: the guided mode, and escaping the answers as HTML — neither this
   nor the script does, and both say so rather than pretending otherwise.
   ========================================================================== */
